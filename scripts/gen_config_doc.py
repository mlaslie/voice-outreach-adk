"""Regenerate docs/CONFIG.md from the pydantic config models (single source of truth).

uv run python scripts/gen_config_doc.py
"""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel
from voa_core.config import AppConfig

OUT = Path(__file__).resolve().parents[1] / "docs" / "CONFIG.md"


def _type(t) -> str:
    return getattr(t, "__name__", None) or str(t).replace("typing.", "")


def rows(model: type[BaseModel], prefix: str = "") -> list[str]:
    out = []
    for name, f in model.model_fields.items():
        ann = f.annotation
        if isinstance(ann, type) and issubclass(ann, BaseModel):
            out += rows(ann, f"{prefix}{name}.")
            continue
        default = "" if f.is_required() else repr(f.get_default(call_default_factory=True))
        env = "VOA__" + (prefix + name).upper().replace(".", "__")
        if prefix + name == "env":
            env = "VOA_ENV"
        desc = (f.description or "").replace("|", "/")
        out.append(f"| `{prefix}{name}` | `{env}` | {_type(ann)} | `{default}` | {desc} |")
    return out


def main() -> None:
    lines = [
        "# Configuration reference",
        "",
        "Generated by `scripts/gen_config_doc.py` from `voa_core.config`. Do not edit by hand.",
        "",
        "Layers (lowest to highest): `config/app.yaml` -> `config/site.yaml` -> "
        "`config/providers/*.yaml` -> `config/environments/$VOA_ENV.yaml` -> `VOA__*` env vars. "
        "`VOA_ENV` itself is authoritative. "
        "Values like `secret://name` are Secret Manager references.",
        "In Cloud Run the env vars are set by Terraform (`infra/envs/<env>/services.tf`).",
        "",
        "| Key | Env var | Type | Default | Notes |",
        "|---|---|---|---|---|",
        *rows(AppConfig),
        "",
        "Provider blocks (`providers.<name>.*`) are free-form and validated by the adapter: "
        "Twilio uses `account_sid`, `api_key_sid`, `api_key_secret`, `auth_token` "
        "(all `secret://`) "
        "and `from_number`.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
