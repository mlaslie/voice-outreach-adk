"""Post-op PARITY: the generic engine must reproduce the pre-refactor outputs exactly.

The goldens in ``golden/`` were generated by ``generate_parity.py`` from the code
BEFORE the use-case engine (docs/USE-CASES-PLAN.md, step 1) and are never
regenerated: a failure here is a behaviour change for post-op, i.e. a bug. If a
change is intended, it needs a clinical decision and a new golden in its own
reviewed commit, not a quiet regeneration.
"""

from __future__ import annotations

import asyncio
import copy
import datetime
import json
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import generate_parity as gp  # noqa: E402

GOLDEN = HERE / "golden"


def _load(name: str):
    return json.loads((GOLDEN / name).read_text())


# --------------------------------------------------------------------------- (a) triage


def test_triage_corpus_is_identical():
    from voa_core import survey

    cases = [c for f in sorted(GOLDEN.glob("triage_*.json")) for c in _load(f.name)]
    assert len(cases) > 3000
    bad = []
    for case in cases:
        got = gp._rt(gp.triage_out(survey.triage(copy.deepcopy(case["answers"]))))
        if got != case["out"]:
            bad.append((case["answers"], case["out"], got))
    assert not bad, f"{len(bad)} triage differences; first: {bad[0]}"


# --------------------------------------------------------------------------- (b) reports


def test_report_validation_is_identical():
    from voa_core import reports

    bad = []
    for case in _load("reports.json"):
        kw = {"call_id_pattern": case["pattern"]} if case["pattern"] else {}
        clean, errors = reports.validate_report(copy.deepcopy(case["payload"]), **kw)
        if errors != case["errors"] or gp._rt(clean) != case["clean"]:
            bad.append((case["payload"], case["errors"], errors, case["clean"], clean))
    assert not bad, f"{len(bad)} report differences; first: {bad[0]}"


# --------------------------------------------------------------------------- (c) instruction


def test_voice_instruction_is_identical():
    from voa_agents.voice.instruction import build_instruction
    from voa_core.campaign import load_campaign

    for case in _load("instruction.json"):
        text = build_instruction(
            load_campaign(case["campaign"]),
            org_name=case["org_name"],
            patient=case["patient"],
            knowledge=case["knowledge"],
        )
        assert text == case["text"], (case["patient"], case["knowledge"])


