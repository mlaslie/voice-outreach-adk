# --------------------------------------------------------------------------- (e) SMS


def test_sms_texts_are_identical():
    want = _load("sms_texts.json")["texts"]
    got = gp._rt(gp.gen_sms_texts())["texts"]
    diff = {k: (want.get(k), got.get(k)) for k in set(want) | set(got) if want.get(k) != got.get(k)}
    assert not diff, diff


