# --------------------------------------------------------------------------- (g) voice tools


def test_voice_tool_sessions_are_identical():
    want = _load("voice_tools.json")
    for case in want:
        if "session" not in case:
            continue
        got = asyncio.run(gp._voice_session(case["steps"], case["initial"]))
        assert gp._rt(got["results"]) == case["results"], (case["state"], case["session"])
        assert gp._rt(got["final_state"]) == case["final_state"], (case["state"], case["session"])
        assert gp._rt(got["audit"]) == case["audit"], (case["state"], case["session"])


def test_voice_closings_are_identical():
    from voa_agents.voice import tools
    from voa_core.campaign import load_campaign

    c = load_campaign("post_op")
    for case in _load("voice_tools.json"):
        if "closing_for" in case:
            tier, asked, with_campaign = case["closing_for"]
            assert tools.closing_for(c if with_campaign else None, tier, asked) == case["out"]
